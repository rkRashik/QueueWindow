export const dictionary = { en, bn };
export type Language = keyof typeof dictionary;
export type Dictionary = typeof en;

export function formatNumber(value: number, language: Language) {
  return new Intl.NumberFormat(language, { maximumFractionDigits: 2 }).format(
    value,
  );
}

export function formatElapsed(seconds: number, language: Language) {
  const minutes = Math.floor(Math.max(0, seconds) / 60);
  const remainder = Math.floor(Math.max(0, seconds) % 60);
  const digits = new Intl.NumberFormat(language, {
    minimumIntegerDigits: 2,
    useGrouping: false,
  });
  return `${digits.format(minutes)}:${digits.format(remainder)}`;
}
